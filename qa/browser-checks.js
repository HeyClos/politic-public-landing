async page => {
  const checks = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  const errors = [];
  page.on('pageerror', err => errors.push(err.message));
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto('http://127.0.0.1:4173/');
  await page.evaluate(() => document.fonts.ready);
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({width,height:1000});
    const size = await page.evaluate(() => ({doc:document.documentElement.scrollWidth,view:innerWidth}));
    assert(size.doc <= size.view, `No horizontal overflow at ${width}px`);
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  assert(await page.locator('#heroMontage').getAttribute('data-motion') === 'paused', 'Animation pause control works');
  await page.getByRole('button',{name:'Play',exact:true}).click();
  assert(await page.locator('#heroMontage').getAttribute('data-motion') === 'playing', 'Animation resumes');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(() => document.getElementById('motion-toggle').disabled);
  assert(await page.locator('#motion-toggle').isDisabled(), 'Reduced motion respected');
  assert(await page.locator('#heroMontage').getAttribute('data-motion') === 'paused', 'Reduced-motion montage is static');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.getByRole('link',{name:'Read a sample'}).click();
  await page.locator('.source-note summary').click();
  assert(await page.locator('.source-note').getAttribute('open') !== null, 'Source note expands');
  assert(await page.getByRole('link',{name:'Clark County meeting records'}).getAttribute('href') === 'https://clark.legistar.com/Calendar.aspx','Source note links to official records');
  await page.locator('[data-open-signup]').first().click();
  assert(await page.locator('#signup-dialog').isVisible(), 'Request access opens native modal');
  await page.keyboard.press('Escape');
  assert(!await page.locator('#signup-dialog').isVisible(), 'Escape closes modal');
  assert(await page.locator('[data-open-signup]').first().evaluate(el => el === document.activeElement), 'Focus returns to opener');
  await page.locator('[data-open-signup]').first().click();
  await page.locator('#signup-submit').click();
  assert(!await page.locator('input[name=email]').evaluate(el => el.validity.valid), 'Required email validation works');
  await page.locator('input[name=email]').fill('qa@example.com');
  await page.locator('input[name=name]').fill('Preview Test');
  await page.locator('input[name=company]').fill('QA organization');
  await page.locator('select[name=role]').selectOption('lobbyist');
  await page.locator('input[value=residential-zoning]').check();
  await page.locator('input[name=zip]').fill('89101');
  let payload;
  await page.route('**/api/signup', async route => {
    payload = route.request().postDataJSON();
    await route.fulfill({status:429,contentType:'application/json',body:'{"ok":false,"error":"rate_limited"}'});
  });
  await page.locator('#signup-submit').click();
  await page.locator('#form-error').filter({hasText:'wait a minute'}).waitFor();
  assert(await page.locator('input[name=email]').inputValue() === 'qa@example.com', 'Failed submit preserves entered details');
  assert(!await page.locator('#signup-submit').isDisabled(), 'Failed submit can be retried');
  await page.unroute('**/api/signup');
  await page.route('**/api/signup', route => route.fulfill({status:200,contentType:'application/json',body:'{"ok":true}'}));
  await page.locator('#signup-submit').click();
  await page.locator('#signup-success').waitFor({state:'visible'});
  assert(payload.role === 'lobbyist' && payload.topics[0] === 'residential-zoning' && payload.zip === '89101' && payload.website === '', 'Signup payload matches live API contract');
  assert(await page.locator('#signup-success h2').evaluate(el => el === document.activeElement), 'Success receives focus');
  await page.getByRole('button',{name:'Back to the page'}).click();
  await page.locator('[data-open-signup]').first().click();
  assert(await page.locator('input[name=email]').inputValue() === '', 'New request resets successful form');
  await page.keyboard.press('Escape');
  await page.unroute('**/api/signup');
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-open-signup]').first().click();
  assert(await page.locator('#signup-dialog').evaluate(el => el.scrollWidth <= el.clientWidth), 'Mobile modal has no horizontal overflow');
  await page.keyboard.press('Escape');
  await page.evaluate(() => scrollTo(0,0));
  await page.screenshot({path:'brand/landing-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(() => scrollTo(0,0));
  await page.screenshot({path:'brand/landing-desktop.png',fullPage:true});
  assert(errors.length === 0, 'No JavaScript runtime errors');
  return {passed:checks.length, checks, errors, note:'All signup POSTs were intercepted; no production signup was submitted.'};
}
